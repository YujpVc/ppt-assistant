#!/usr/bin/env python3
"""Shared layout budget ledger for multi-part decks.

Parts generated by different agents claim a layout before drawing a page.  The
ledger is process-safe (fcntl) so concurrent parts do not all choose `sequence`.
"""
from __future__ import annotations

import argparse
import fcntl
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

DEFAULT = Path.home() / ".cache/ppt-assistant/layout-ledger.json"
ALLOWED = [
    "section_number", "architecture", "route_map", "flow_chart", "glass_canvas",
    "sequence", "pillars", "matrix", "briefing", "image_panel", "image_panel_strip",
    "figure_annotated", "evidence_grid", "compare_grid", "academic_table",
    "image_band", "image_mosaic", "glass_overlay", "light_cover", "image_hero",
    "image_statement", "section_number", "blocks", "image_arch",
]


def load(path: Path) -> dict:
    if path.is_file():
        return json.loads(path.read_text(encoding="utf-8"))
    return {"claims": []}


def save(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def counts(data: dict) -> dict[str, int]:
    out: dict[str, int] = {}
    for claim in data.get("claims", []):
        layout = claim.get("layout", "")
        out[layout] = out.get(layout, 0) + 1
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["status", "claim"])
    parser.add_argument("--file", type=Path, default=DEFAULT)
    parser.add_argument("--layout")
    parser.add_argument("--owner", default="")
    parser.add_argument("--page", default="")
    parser.add_argument("--cap", type=int, default=2)
    args = parser.parse_args()
    args.file.parent.mkdir(parents=True, exist_ok=True)
    with args.file.open("a+", encoding="utf-8") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        handle.seek(0)
        try:
            data = json.load(handle)
        except json.JSONDecodeError:
            data = {"claims": []}
        used = counts(data)
        if args.action == "status":
            print(json.dumps({"counts": used, "cap": args.cap}, ensure_ascii=False, indent=2))
            return 0
        if not args.layout:
            print("claim requires --layout", file=sys.stderr)
            return 2
        if args.layout not in ALLOWED and not args.layout.startswith("custom_"):
            print(f"unknown layout: {args.layout}", file=sys.stderr)
            return 2
        if used.get(args.layout, 0) >= args.cap:
            print(json.dumps({
                "ok": False, "layout": args.layout, "count": used.get(args.layout, 0),
                "reason": f"layout budget {args.cap} reached",
                "alternatives": [x for x in ALLOWED if used.get(x, 0) < args.cap][:8],
            }, ensure_ascii=False, indent=2))
            return 3
        data.setdefault("claims", []).append({
            "layout": args.layout, "owner": args.owner, "page": args.page,
            "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        })
        save(args.file, data)
        print(json.dumps({"ok": True, "layout": args.layout,
                          "count": used.get(args.layout, 0) + 1,
                          "cap": args.cap}, ensure_ascii=False, indent=2))
        return 0


if __name__ == "__main__":
    raise SystemExit(main())
